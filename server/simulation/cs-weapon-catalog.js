const WEAPON_LIST = Object.freeze(Object.values(WEAPONS));

function getWeapon(name) {
  return WEAPONS[name] || WEAPONS['AK-47'];
}

function weaponsForSide(side, category = null) {
  return WEAPON_LIST.filter(weapon =>
    (weapon.side === 'ANY' || weapon.side === side)
    && (!category || weapon.category === category)
  );
}

function starterWeapon(side) {
  return side === 'CT' ? WEAPONS['USP-S'] : WEAPONS['Glock-18'];
}

function rifleWeapon(side) {
  return side === 'CT' ? WEAPONS['M4A1-S'] : WEAPONS['AK-47'];
}

